public class Kandydat {
    private String pesel;
    private String imie;

    public Kandydat(String pesel, String imie) {
        this.pesel = pesel;
        this.imie = imie;
    }

    public String getPesel() {
        return pesel;
    }

    public String getImie() {
        return imie;
    }
}